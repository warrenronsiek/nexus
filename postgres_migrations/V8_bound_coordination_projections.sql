CREATE FUNCTION pg_temp.nexus_v8_bound_text(value TEXT, maximum_bytes INTEGER)
RETURNS TEXT
LANGUAGE plpgsql
IMMUTABLE
STRICT
AS $$
DECLARE
    low INTEGER := 0;
    high INTEGER := LEAST(char_length(value), maximum_bytes);
    middle INTEGER;
BEGIN
    IF octet_length(value) <= maximum_bytes THEN
        RETURN value;
    END IF;
    WHILE low < high LOOP
        middle := (low + high + 1) / 2;
        IF octet_length(left(value, middle)) <= maximum_bytes THEN
            low := middle;
        ELSE
            high := middle - 1;
        END IF;
    END LOOP;
    RETURN left(value, low);
END;
$$;

CREATE TEMP TABLE nexus_v8_path_map (
    mapping_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id TEXT NOT NULL,
    old_path TEXT NOT NULL,
    new_path TEXT,
    UNIQUE(project_id, old_path),
    UNIQUE(project_id, new_path)
) ON COMMIT DROP;

INSERT INTO nexus_v8_path_map(project_id, old_path)
SELECT project_id, old_path
FROM (
    SELECT project_id, path AS old_path FROM claims WHERE octet_length(path) > 4096
    UNION
    SELECT project_id, path AS old_path FROM conflicts WHERE octet_length(path) > 4096
    UNION
    SELECT project_id, path AS old_path FROM advisories WHERE octet_length(path) > 4096
) oversized_paths
ORDER BY project_id, old_path;

DO $migration$
DECLARE
    mapping RECORD;
    attempt BIGINT;
    candidate TEXT;
BEGIN
    FOR mapping IN
        SELECT mapping_id, project_id, old_path
        FROM nexus_v8_path_map
        ORDER BY mapping_id
    LOOP
        attempt := 0;
        LOOP
            IF attempt = 0 THEN
                candidate := pg_temp.nexus_v8_bound_text(mapping.old_path, 4070)
                    || '~nexus-v8-'
                    || lpad(to_hex(mapping.mapping_id), 16, '0');
            ELSE
                candidate := pg_temp.nexus_v8_bound_text(mapping.old_path, 4053)
                    || '~nexus-v8-'
                    || lpad(to_hex(mapping.mapping_id), 16, '0')
                    || '-'
                    || lpad(to_hex(attempt), 16, '0');
            END IF;

            EXIT WHEN NOT EXISTS (
                SELECT 1 FROM claims
                WHERE project_id = mapping.project_id AND path = candidate
            ) AND NOT EXISTS (
                SELECT 1 FROM conflicts
                WHERE project_id = mapping.project_id AND path = candidate
            ) AND NOT EXISTS (
                SELECT 1 FROM advisories
                WHERE project_id = mapping.project_id AND path = candidate
            ) AND NOT EXISTS (
                SELECT 1 FROM nexus_v8_path_map
                WHERE project_id = mapping.project_id AND new_path = candidate
            );
            attempt := attempt + 1;
        END LOOP;

        UPDATE nexus_v8_path_map
        SET new_path = candidate
        WHERE mapping_id = mapping.mapping_id;
    END LOOP;
END;
$migration$;

UPDATE claims
SET path = nexus_v8_path_map.new_path
FROM nexus_v8_path_map
WHERE nexus_v8_path_map.project_id = claims.project_id
  AND nexus_v8_path_map.old_path = claims.path;

UPDATE conflicts
SET path = nexus_v8_path_map.new_path
FROM nexus_v8_path_map
WHERE nexus_v8_path_map.project_id = conflicts.project_id
  AND nexus_v8_path_map.old_path = conflicts.path;

UPDATE advisories
SET path = nexus_v8_path_map.new_path
FROM nexus_v8_path_map
WHERE nexus_v8_path_map.project_id = advisories.project_id
  AND nexus_v8_path_map.old_path = advisories.path;

CREATE TEMP TABLE nexus_v8_claim_id_map (
    mapping_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    old_claim_id TEXT NOT NULL UNIQUE,
    new_claim_id TEXT UNIQUE
) ON COMMIT DROP;

INSERT INTO nexus_v8_claim_id_map(old_claim_id)
SELECT old_claim_id
FROM (
    SELECT id AS old_claim_id FROM claims WHERE octet_length(id) > 512
    UNION
    SELECT left_claim_id AS old_claim_id FROM conflicts WHERE octet_length(left_claim_id) > 512
    UNION
    SELECT right_claim_id AS old_claim_id FROM conflicts WHERE octet_length(right_claim_id) > 512
) oversized_claim_ids
ORDER BY old_claim_id;

DO $migration$
DECLARE
    mapping RECORD;
    attempt BIGINT;
    candidate TEXT;
BEGIN
    FOR mapping IN
        SELECT mapping_id FROM nexus_v8_claim_id_map ORDER BY mapping_id
    LOOP
        attempt := 0;
        LOOP
            candidate := 'nexus-v8-claim-'
                || lpad(to_hex(mapping.mapping_id), 16, '0');
            IF attempt > 0 THEN
                candidate := candidate || '-' || lpad(to_hex(attempt), 16, '0');
            END IF;

            EXIT WHEN NOT EXISTS (
                SELECT 1 FROM claims WHERE id = candidate
            ) AND NOT EXISTS (
                SELECT 1 FROM conflicts WHERE left_claim_id = candidate
            ) AND NOT EXISTS (
                SELECT 1 FROM conflicts WHERE right_claim_id = candidate
            ) AND NOT EXISTS (
                SELECT 1 FROM nexus_v8_claim_id_map WHERE new_claim_id = candidate
            );
            attempt := attempt + 1;
        END LOOP;

        UPDATE nexus_v8_claim_id_map
        SET new_claim_id = candidate
        WHERE mapping_id = mapping.mapping_id;
    END LOOP;
END;
$migration$;

UPDATE conflicts
SET left_claim_id = nexus_v8_claim_id_map.new_claim_id
FROM nexus_v8_claim_id_map
WHERE conflicts.left_claim_id = nexus_v8_claim_id_map.old_claim_id;

UPDATE conflicts
SET right_claim_id = nexus_v8_claim_id_map.new_claim_id
FROM nexus_v8_claim_id_map
WHERE conflicts.right_claim_id = nexus_v8_claim_id_map.old_claim_id;

UPDATE claims
SET id = nexus_v8_claim_id_map.new_claim_id
FROM nexus_v8_claim_id_map
WHERE claims.id = nexus_v8_claim_id_map.old_claim_id;

CREATE TEMP TABLE nexus_v8_tool_id_map (
    mapping_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id TEXT NOT NULL,

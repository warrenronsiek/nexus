CREATE TEMP TABLE nexus_v8_session_id_map (
    mapping_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    old_session_id TEXT NOT NULL UNIQUE,
    new_session_id TEXT UNIQUE
) ON COMMIT DROP;

INSERT INTO nexus_v8_session_id_map(old_session_id)
SELECT old_session_id
FROM (
    SELECT session_id AS old_session_id
    FROM sessions WHERE octet_length(session_id) > 512
    UNION
    SELECT session_id AS old_session_id
    FROM claims WHERE octet_length(session_id) > 512
) oversized_session_ids
ORDER BY old_session_id;

DO $migration$
DECLARE
    mapping RECORD;
    attempt BIGINT;
    candidate TEXT;
BEGIN
    FOR mapping IN
        SELECT mapping_id FROM nexus_v8_session_id_map ORDER BY mapping_id
    LOOP
        attempt := 0;
        LOOP
            candidate := 'nexus-v8-session-'
                || lpad(to_hex(mapping.mapping_id), 16, '0');
            IF attempt > 0 THEN
                candidate := candidate || '-' || lpad(to_hex(attempt), 16, '0');
            END IF;

            EXIT WHEN NOT EXISTS (
                SELECT 1 FROM events WHERE session_id = candidate
            ) AND NOT EXISTS (
                SELECT 1 FROM sessions WHERE session_id = candidate
            ) AND NOT EXISTS (
                SELECT 1 FROM claims WHERE session_id = candidate
            ) AND NOT EXISTS (
                SELECT 1 FROM advisories WHERE session_id = candidate
            ) AND NOT EXISTS (
                SELECT 1 FROM capability_uses WHERE session_id = candidate
            ) AND NOT EXISTS (
                SELECT 1 FROM memory_entries WHERE session_id = candidate
            ) AND NOT EXISTS (
                SELECT 1 FROM memory_activations WHERE session_id = candidate
            ) AND NOT EXISTS (
                SELECT 1 FROM papercuts WHERE creator_session_id = candidate
            ) AND NOT EXISTS (
                SELECT 1 FROM papercut_upvotes WHERE reporter_session_id = candidate
            ) AND NOT EXISTS (
                SELECT 1 FROM papercut_duplicate_reviews
                WHERE reporter_session_id = candidate OR reviewer_session_id = candidate
            ) AND NOT EXISTS (
                SELECT 1 FROM nexus_v8_session_id_map WHERE new_session_id = candidate
            );
            attempt := attempt + 1;
        END LOOP;

        UPDATE nexus_v8_session_id_map
        SET new_session_id = candidate
        WHERE mapping_id = mapping.mapping_id;
    END LOOP;
END;
$migration$;

UPDATE events

SET session_id = nexus_v8_session_id_map.new_session_id
FROM nexus_v8_session_id_map
WHERE nexus_v8_session_id_map.old_session_id = sessions.session_id;

UPDATE sessions
SET agent = pg_temp.nexus_v8_bound_text(agent, 256)
WHERE octet_length(agent) > 256;

UPDATE sessions
SET worktree = pg_temp.nexus_v8_bound_text(worktree, 4096)
WHERE worktree IS NOT NULL AND octet_length(worktree) > 4096;

UPDATE sessions
SET task_summary = pg_temp.nexus_v8_bound_text(task_summary, 1024)
WHERE task_summary IS NOT NULL AND octet_length(task_summary) > 1024;

UPDATE conflicts
SET message = pg_temp.nexus_v8_bound_text(message, 8192)
WHERE octet_length(message) > 8192;

ALTER TABLE sessions
ADD CONSTRAINT sessions_projection_width
CHECK (
    octet_length(session_id) <= 512
    AND octet_length(agent) <= 256
    AND (worktree IS NULL OR octet_length(worktree) <= 4096)
    AND (task_summary IS NULL OR octet_length(task_summary) <= 1024)
);

ALTER TABLE claims
ADD CONSTRAINT claims_projection_width
CHECK (
    octet_length(id) <= 512
    AND octet_length(session_id) <= 512
    AND octet_length(tool_use_id) <= 512
    AND octet_length(path) <= 4096
);

ALTER TABLE conflicts
ADD CONSTRAINT conflicts_projection_width
CHECK (
    octet_length(left_claim_id) <= 512
    AND octet_length(right_claim_id) <= 512
    AND octet_length(path) <= 4096
    AND octet_length(message) <= 8192
);

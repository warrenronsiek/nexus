#!/usr/bin/env python3
# @feature installation
# @feature runtime
# @spec docs/features/installation.md
# @spec docs/features/runtime.md
# @boundary compose-browser-credentials: private bounded setup output is streamed to the service UID; verifier bytes never become arguments or diagnostic output.
"""Copy a setup-generated browser verifier into the existing service volume."""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import stat
import subprocess
import sys

INSTALL = """set -eu
umask 077
target=/var/lib/nexus/web-credentials.json
pending=$(mktemp "${target}.pending.XXXXXX")
trap '[ -z "$pending" ] || rm "$pending"' EXIT
cat > "$pending"
test -s "$pending"
chmod 600 "$pending"
mv "$pending" "$target"
pending=
"""


def credential_bytes(path: Path) -> bytes:
    descriptor = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    with os.fdopen(descriptor, "rb") as stream:
        metadata = os.fstat(stream.fileno())
        if not stat.S_ISREG(metadata.st_mode) or metadata.st_uid != os.geteuid() or metadata.st_mode & 0o077:
            raise ValueError("browser credential source must be a private owned regular file (0600 or stricter)")
        content = stream.read(4097)
    if not content or len(content) > 4096:
        raise ValueError("browser credential source must contain at most 4096 bytes")
    try:
        record = json.loads(content)
        valid = (
            isinstance(record, dict) and set(record) == {"version", "username", "password_hash"}
            and record["version"] == 1 and isinstance(record["username"], str)
            and isinstance(record["password_hash"], str) and record["password_hash"].startswith("$argon2id$")
        )
    except (ValueError, UnicodeError):
        valid = False
    if not valid:
        raise ValueError("browser credential source must be a verifier generated by nexus setup")
    return content


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("credentials", type=Path)
    parser.add_argument("compose", nargs=argparse.REMAINDER)
    args = parser.parse_args()
    try:
        content = credential_bytes(args.credentials)
        if not args.check:
            compose = args.compose[1:] if args.compose[:1] == ["--"] else args.compose
            if not compose:
                parser.error("a Docker Compose command is required after --")
            subprocess.run([*compose, "run", "--rm", "--no-deps", "-T", "--entrypoint", "sh", "nexus", "-ec", INSTALL], input=content, check=True)
        return 0
    except (OSError, ValueError, subprocess.CalledProcessError):
        print("Browser credential provisioning failed; use a private owned setup-generated verifier file and a writable Nexus service volume.", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())

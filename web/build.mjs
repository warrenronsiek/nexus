// @feature observability-ui
// @spec docs/features/observability-ui.md
// @boundary package-license-metadata: build-time npm and Elm package descriptors provide pinned runtime license inventory only.
import { build } from "vite";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { homedir } from "node:os";

await build();
const packages = new Set();
function includePackage(name) {
  if (packages.has(name)) return;
  packages.add(name);
  const metadata = JSON.parse(readFileSync(join("node_modules", name, "package.json"), "utf8"));
  Object.keys(metadata.dependencies ?? {}).forEach(includePackage);
}
["d3", "@fontsource/public-sans", "@fontsource/ibm-plex-mono", "lucide-static"].forEach(includePackage);
const licenseSections = [...packages].sort().map(name => {
  const directory = join("node_modules", name), metadata = JSON.parse(readFileSync(join(directory, "package.json"), "utf8"));
  return `${name} ${metadata.version}\n${readFileSync(join(directory, "LICENSE"), "utf8").trim()}`;
});
const elm = JSON.parse(readFileSync("elm.json", "utf8"));
for (const [name, version] of Object.entries({ ...elm.dependencies.direct, ...elm.dependencies.indirect }).sort(([a], [b]) => a.localeCompare(b))) {
  const license = readFileSync(join(process.env.ELM_HOME ?? join(homedir(), ".elm"), "0.19.1", "packages", name, version, "LICENSE"), "utf8");
  licenseSections.push(`${name} ${version}\n${license.trim()}`);
}
writeFileSync("dist/THIRD_PARTY_LICENSES.txt", licenseSections.join("\n\n----------------------------------------\n\n") + "\n");
const files = readdirSync("dist", { recursive: true, withFileTypes: true }).filter(file => file.isFile()).map(file => join(file.parentPath, file.name).replaceAll("\\", "/").replace(/^.*\/dist\//, "").replace(/^dist\//, "")).sort();
const contentTypes = { html: "text/html; charset=utf-8", js: "text/javascript; charset=utf-8", css: "text/css; charset=utf-8", txt: "text/plain; charset=utf-8", svg: "image/svg+xml", woff2: "font/woff2", woff: "font/woff" };
const mime = path => contentTypes[path.split(".").at(-1)] ?? "application/octet-stream";
const aliases = ["/", "/ui", "/ui/", ...["coordination", "work", "evals", "tools", "skills", "concerns", "papercuts", "sos", "memory"].map(name => `/ui/${name}`)];
const entries = [...aliases.map(path => [path, "index.html"]), ...files.map(path => [`/${path}`, path])];
writeFileSync("dist/embedded.rs", `// @feature observability-ui\n// @spec docs/features/observability-ui.md\n// Generated by web/build.mjs; the asset whitelist contains no filesystem fallback.\npub(super) fn asset(path: &str) -> Option<(&'static str, &'static [u8])> {\n    match path {\n${entries.map(([route, path]) => `        ${JSON.stringify(route)} => Some((${JSON.stringify(mime(path))}, include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), "/web/dist/${path}")))),`).join("\n")}\n        _ => None,\n    }\n}\n`);
